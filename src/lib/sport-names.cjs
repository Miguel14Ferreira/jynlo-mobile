const key=v=>String(v).normalize('NFD').replace(/[̀-ͯ]/g,'').trim().toLowerCase().replace(/\s+/g,' ');
const index=table=>Object.fromEntries(Object.entries(table).map(([pt,en])=>[key(pt),en]));
const TABLES={sport:index(EN_SPORTS),venueType:index(EN_VENUE_TYPES),surface:index(EN_SURFACES)};
function label(kind,value,language){
 if(value==null||value==='')return '';
 const text=String(value);
 if((language||currentLanguage())!=='en')return text;
 return TABLES[kind][key(text)]??text;
}
/** Sport name to show: English in the English app, the stored value otherwise. Unknown names stay as they are. */
function sportName(value,language){return label('sport',value,language);}
/** A comma-separated list of sports ("Futebol, Padel"). */
function sportNames(value,language){
 if(value==null||value==='')return '';
 return String(value).split(',').map(s=>s.trim()).filter(Boolean).map(s=>sportName(s,language)).join(', ');
}
function venueTypeName(value,language){return label('venueType',value,language);}
function surfaceName(value,language){return label('surface',value,language);}
/** Search a sport by its Portuguese or English name (accents and case ignored). */
function sportMatches(value,query){
 const q=key(query||'');
 if(!q)return true;
 const en=TABLES.sport[key(value)];
 return key(value).includes(q)||(!!en&&key(en).includes(q));
}
module.exports={EN_SPORTS,EN_VENUE_TYPES,EN_SURFACES,sportName,sportNames,venueTypeName,surfaceName,sportMatches};
