const untranslate=require('./untranslate.cjs');
'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process');
const read=p=>untranslate(fs.readFileSync(path.join(__dirname,'..',p),'utf8'));
test('Google Play só pode enviar através de workflow_dispatch em develop e confirmação explícita',()=>{
 const yaml=read('.github/workflows/upload-play-internal.yml');
 assert.match(yaml,/workflow_dispatch:/);
 assert.doesNotMatch(yaml,/\n\s*push:/);
 assert.match(yaml,/github.ref == 'refs\/heads\/develop'/);
 assert.match(yaml,/ENVIAR_JYNLO_TESTE_INTERNO/);
 assert.match(yaml,/default: verify-auth/);
 assert.match(yaml,/verify-artifact/);
 assert.match(yaml,/inputs.action == 'verify-artifact'/);
 assert.match(yaml,/Confirmação de validação sem publicação/);
 assert.match(yaml,/default: draft/);
 assert.match(yaml,/run-id: \$\{\{ inputs.build_run_id \}\}/);
 assert.match(yaml,/--version "\$V" --version-code "\$C" --commit "\$G"/);
 assert.match(yaml,/inputs.action == 'upload'/);
 assert.match(yaml,/inputs.confirm == 'ENVIAR_JYNLO_TESTE_INTERNO'/);
 assert.doesNotMatch(yaml,/:app:bundleRelease|:app:assembleRelease/);
});
test('Autenticação usa OIDC sem chaves privadas e publicação fica limitada à faixa interna',()=>{
 const yaml=read('.github/workflows/upload-play-internal.yml');
 const py=read('scripts/play_upload_internal.py');
 assert.match(yaml,/id-token: write/);
 assert.match(yaml,/google-github-actions\/auth@v3/);
 assert.match(yaml,/projects\/955491875786\/locations\/global\/workloadIdentityPools\/jynlo-github\/providers\/github-actions/);
 assert.match(yaml,/jynlo-play-publisher@jynlo-play-store\.iam\.gserviceaccount\.com/);
 assert.match(yaml,/Confirmar autenticação federada \(sem publicar\)/);
 assert.match(py,/google\.auth\.default/);
 assert.match(py,/TRACK="internal"/);
 assert.match(py,/--apply/);
 assert.match(py,/edits\(\)\.commit/);
 assert.match(py,/file_digest/);
 assert.doesNotMatch(py,/from_service_account_info|SERVICE_ACCOUNT_JSON/);
 assert.doesNotMatch(yaml,/JYNLO_GOOGLE_PLAY_SERVICE_ACCOUNT_JSON|track: production/);
 assert.doesNotMatch(py,/TRACK="production"/);
});
test('O script de publicação é Python válido',()=>{
 const py=path.join(__dirname,'../scripts/play_upload_internal.py');
 cp.execFileSync('python3',['-c','import ast,sys;ast.parse(open(sys.argv[1],encoding="utf-8").read())',py],{stdio:'pipe'});
});
